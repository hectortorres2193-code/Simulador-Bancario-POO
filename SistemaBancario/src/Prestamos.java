    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        BigDecimal monto = BigDecimal.valueOf(jSliderMonto.getValue());
    int meses = plazoSeleccionado;

    List<CuotaAmortizacion> tabla = controller.simularPrestamo(monto, meses);
    BigDecimal pagoMensual = tabla.get(0).getCuota();
    BigDecimal total = pagoMensual.multiply(BigDecimal.valueOf(meses));

    // Estos son los 4 del panel derecho:
    jlTasa.setText("Tasa de interés: " + controller.getTasaAnual() + " anual");
    jlPlazo.setText("Plazo seleccionado: " + meses + " meses");
    jlPagoMensual.setText("Pago mensual estimado: $" + pagoMensual + " MXN");
    jlTotal.setText("Total a pagar: $" + total + " MXN");
    }//GEN-LAST:event_jButton4ActionPerformed

