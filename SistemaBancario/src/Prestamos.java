    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
         java.math.BigDecimal monto = java.math.BigDecimal.valueOf(jSliderMonto.getValue());
    int meses = plazoSeleccionado;

    try {
        java.util.List<com.banco.amortizacion.CuotaAmortizacion> tabla = controller.aceptarPrestamo(monto, meses);
        javax.swing.JOptionPane.showMessageDialog(this,
            "¡Préstamo solicitado con éxito!\n\n" +
            "Monto: $" + monto + " MXN\n" +
            "Plazo: " + meses + " meses\n" +
            "Cuotas generadas: " + tabla.size(),
            "Préstamo Aprobado", javax.swing.JOptionPane.INFORMATION_MESSAGE);
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Error al solicitar: " + e.getMessage(),
            "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton1ActionPerformed

