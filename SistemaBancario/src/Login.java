    // Crea el reloj y el escucha de mouse/teclado
    private void iniciarTemporizadorInactividad() {
    // Crea un Timer de 10000 ms = 10 segundos, si se cumple llama a cerrarPorInactividad()
    timerInactividad = new javax.swing.Timer(10000, e -> {cerrarPorInactividad();});
    //  Que no se repita solo, solo una vez
    timerInactividad.setRepeats(false);
    timerInactividad.start();
    //  Listener que detecta si hay actividad de mouse o teclado
    listenerInactividad = event -> {
        if (event instanceof java.awt.event.MouseEvent || event instanceof java.awt.event.KeyEvent) {
            if (this.isDisplayable()) {
                reiniciarTemporizador();
            }
        }
    };
    //  Registra el listener en todo el sistema para que escuche teclado y mouse
    java.awt.Toolkit.getDefaultToolkit().addAWTEventListener(listenerInactividad,
        java.awt.AWTEvent.KEY_EVENT_MASK | java.awt.AWTEvent.MOUSE_EVENT_MASK | java.awt.AWTEvent.MOUSE_MOTION_EVENT_MASK);
    }
//  Vuelve a poner el reloj en 10 segundos desde cero
private void reiniciarTemporizador() {
    if (timerInactividad != null) {
        timerInactividad.restart();
    }
}
//  Apaga el reloj y quita el listener
private void detenerTemporizador() {
    if (timerInactividad != null) {
        timerInactividad.stop();
    }
    if (listenerInactividad != null) {
        java.awt.Toolkit.getDefaultToolkit().removeAWTEventListener(listenerInactividad);
        listenerInactividad = null;
    }
}
// Se ejecuta cuando pasan 10 seg sin actividad, regresa a Inicio y cierra Login
private void cerrarPorInactividad() {
    detenerTemporizador();

    Inicio inicio = new Inicio();
    setExtendedState(Inicio.MAXIMIZED_BOTH); 
    inicio.setResizable(false);
    inicio.setVisible(true);
    this.dispose();
}
  
   
