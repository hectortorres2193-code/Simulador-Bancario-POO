    private void jbEntActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbEntActionPerformed
        // TODO add your handling code here:
    // Botón ENTRAR. La Vista solo pide al Controller que valide, no valida ella
    new PersistenciaController(new CsvRepositorio()).cargarAlIniciar();
    // Toma lo que escribiste en usuario y le quita espacios
    String usuario = jtUsu.getText().trim();
    //  Toma lo que escribiste en NIP
    String clave = new String(jtNip.getPassword());
    // Si usuario o clave están vacíos, avisa y no sigue
    if (usuario.isEmpty() || clave.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Escribe usuario y contraseña");
        return;
    }
    // Crea el Controller que va a validar
    LoginController controller = new LoginController();
    //  Le pregunta al Controller si sí puede entrar, la Vista no sabe cómo valida
    boolean entro = controller.iniciarSesion(usuario, clave);
    

    if (!entro) {
        JOptionPane.showMessageDialog(this, "Usuario o contraseña incorrectos");
        return;
    }

    Rol rol = controller.getRolActual();
    JOptionPane.showMessageDialog(this, "Bienvenido " + usuario);
    // Abre la ventana según el rol, GERENTE abre Admin, CLIENTE abre SecionIniciada
    if (rol == Rol.GERENTE) {
        new Admin().setVisible(true);
    } else if (rol == Rol.CLIENTE) {
        new SecionIniciada().setVisible(true);
    }
        
       
       detenerTemporizador(); 
       // Cierra esta ventana de Login
       this.dispose();
    }//GEN-LAST:event_jbEntActionPerformed

