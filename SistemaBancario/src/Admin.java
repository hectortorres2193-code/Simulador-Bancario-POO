    private void jbPagoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbPagoActionPerformed
        // TODO add your handling code here:
        String idCliente = JOptionPane.showInputDialog("Escriba el ID del cliente");
    String idPrestamo = JOptionPane.showInputDialog("Escriba el ID del préstamo a pagar");

    try {
        controller.registrarPago(idPrestamo);
        JOptionPane.showMessageDialog(this, "Pago de cuota registrado con éxito.");
    } catch (SaldoInsuficienteException e) {
        JOptionPane.showMessageDialog(this, "El cliente no tiene saldo suficiente para la cuota.");
    } catch (IllegalArgumentException | IllegalStateException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_jbPagoActionPerformed

