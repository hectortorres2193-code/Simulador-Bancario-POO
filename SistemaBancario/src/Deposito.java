    private void jlPaAncestorAdded(javax.swing.event.AncestorEvent evt) {//GEN-FIRST:event_jlPaAncestorAdded
        // TODO add your handling code here:
        var prestamos = controller.getPrestamosActivos();

        if (prestamos.isEmpty()) {
              jlPa.setText("No tienes préstamos activos");
        } else {
         String texto = "<html>";

        for (var p : prestamos) {
            int plazo = p.getPlazoMeses();
            BigDecimal pagoMensual = controller.simularPrestamo(p.getMontoOriginal(), plazo).get(0).getCuota();

            texto += "Préstamo activo: " + p.isActivo() + "<br>" +
                     "Plazo: " + plazo + " meses<br>" +
                     "Pago mensual: $" + pagoMensual + "<br><br>";
        }

        texto += "</html>";
        jlPa.setText(texto);
    }
    }//GEN-LAST:event_jlPaAncestorAdded

