    private void btConActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btConActionPerformed
        // TODO add your handling code here:
    try {
    int pestaña = jMenu.getSelectedIndex();

    // Préstamo no toca dinero aquí, solo avisa y regresa
    if (pestaña == 1) {
        JOptionPane.showMessageDialog(this, "Préstamo revisado.");
        new SecionIniciada().setVisible(true);
        this.dispose();
        return;
    }

    // Usa pantallaActiva() que ya existe, así ya no repites jlPan y jlPantalla
    BigDecimal monto = new BigDecimal(pantallaActiva().getText());

    if (pestaña == 0) {
        cuentaController.retirar(monto);
        JOptionPane.showMessageDialog(this, "Retiro realizado con éxito.");
    } else {
        cuentaController.depositar(monto);
        JOptionPane.showMessageDialog(this, "Depósito realizado con éxito.");
    }

    new SecionIniciada().setVisible(true);
    this.dispose();

    } catch (SaldoInsuficienteException e) {
         JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    } catch (NumberFormatException e) {
         JOptionPane.showMessageDialog(this, "Monto no válido.", "Error", JOptionPane.ERROR_MESSAGE);
 
    }//GEN-LAST:event_btConActionPerformed
    }
    
